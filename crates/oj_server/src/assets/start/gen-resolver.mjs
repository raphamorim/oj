// Scan src/ for `createServerFn().handler()` declarations and generate the
// server-fn resolver module (#tanstack-start-server-fn-resolver): a manifest
// mapping functionId -> a dynamic import of the module's exported handler.
// The functionId must match the client transform's createClientRpc(id).
import { readdirSync, statSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const APP = process.env.OJ_APP_ROOT ?? process.cwd();
const SRC = join(APP, "src");

const re = /(?:export\s+)?const\s+([A-Za-z_$][\w$]*)\s*=\s*createServerFn\b[\s\S]*?\.handler\s*\(/g;
const entries = [];

function walk(dir) {
  let names = [];
  try { names = readdirSync(dir); } catch { return; }
  for (const name of names) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) { walk(p); continue; }
    if (!/\.(ts|tsx)$/.test(name)) continue;
    const code = readFileSync(p, "utf8");
    if (!code.includes("createServerFn")) continue;
    re.lastIndex = 0;
    let m;
    while ((m = re.exec(code))) {
      const fn = m[1];
      entries.push({
        id: Buffer.from(`${relative(APP, p)}#${fn}`).toString("base64url"),
        functionName: `${fn}_createServerFn_handler`,
        path: p,
      });
    }
  }
}
walk(SRC);

// Static relative imports so this resolves in BOTH the dev loader hook and the
// bundled production server (esbuild follows the imports; a runtime
// `import(.ts)` would fail in the bundle).
const imports = entries.map((e, i) => {
  const spec = relative(HERE, e.path).replace(/\\/g, "/");
  return { ...e, var: `__m${i}`, spec: spec.startsWith(".") ? spec : `./${spec}` };
});
const importLines = imports.map((e) => `import * as ${e.var} from ${JSON.stringify(e.spec)};`).join("\n");
const manifest = imports
  .map((e) => `  ${JSON.stringify(e.id)}: { functionName: ${JSON.stringify(e.functionName)}, module: ${e.var} },`)
  .join("\n");

const out = `// Generated by oj. Maps server-function ids to their handlers.
${importLines}
const manifest = {
${manifest}
};
export async function getServerFnById(id) {
  const info = manifest[id];
  if (!info) throw new Error("oj: server function not found: " + id);
  return info.module[info.functionName];
}
`;
writeFileSync(join(HERE, "server-fn-resolver.mjs"), out);
const OJ = process.stderr.isTTY && !process.env.NO_COLOR ? "\x1b[1;38;2;42;51;212moj\x1b[0m" : "oj";
process.stderr.write(`${OJ}: server-fn resolver (${entries.length} function(s))\n`);
